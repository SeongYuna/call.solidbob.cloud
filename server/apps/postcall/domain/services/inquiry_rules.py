"""D-2 문의 유형 **제안** — 지식베이스 장(章) 어휘로 고객 확정 발화를 가른다(`decisions/323`).

전에는 「유형을 가를 규칙표가 없다 — 없는 규칙으로 분류하면 그게 지어낸 값이다」로 늘 None 이었고
운영 24/24 가 NULL 이었다. 규칙표를 **지식베이스(`knowledge-base/dasan/terms/TERM.md`)의 장 구분과 조항 제목**에서 만든다 —
유형 이름은 장 이름이고, 어휘는 그 장 조항 제목에 실제로 있는 말이다. 새 분류 체계를 지어내지 않는다.

- 고객 발화만 본다 — 문의 유형은 「고객이 무엇을 물었나」다
- **처음 걸린 고객 발화가 정한다** — 곁가지 질문보다 처음 문의가 유형이다. 한 발화에 두 장이 걸리면 많이 걸린 쪽, 같으면 표 순서
- 어느 장에도 안 걸리면 **「미분류」** — NULL 은 「통화 후 처리 전」이라서(`call_list_dto`) 처리했는데 못 가른 것과 섞이면 안 된다(`w6-d2-inquiry-type-null`)
- 1장 총칙(안내 원칙·신분 확인)은 유형이 아니라 넣지 않았다. 「여권」·「신분증」 은 모든 장에 나오는 서류라 어휘에서 뺐다

⚠ **측정한 적 없다** — 골든셋 D 케이스가 0건이다. 정확도를 말하지 않는다(절대 원칙 2). 상담원이 확정 화면에서 고친다(`310`).
"""

from __future__ import annotations

from .summary_rules import Utterance

UNCLASSIFIED = "미분류"

# (유형 — 장 이름, 30자 이내) → 그 장 조항 제목에서 뽑은 어휘. 표 순서가 동점 순서다
INQUIRY_RULES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("대중교통", ("버스", "지하철", "교통카드", "콜택시", "정기권", "환승", "노선", "분실물", "고속버스", "기차", "교통약자", "길찾기")),  # 2장
    ("상하수도", ("수도", "하수도", "계량기", "누수", "단수", "수질", "급수", "배관", "세대분할", "전자고지")),  # 3장
    ("일반행정", ("증명서", "초본", "등본", "전입", "인감", "본인서명", "청소년증", "지방세", "자동차세", "취득세", "재산세",
                "아동수당", "다자녀", "특별공급", "귀농", "귀촌", "대관", "도서관", "안심택배", "과태료", "주정차", "속도위반", "축제")),  # 4장
    ("감염병", ("코로나", "감염", "방역", "격리", "확진", "예방접종", "백신", "생활지원비", "유급휴가")),  # 5장
    ("재난·생계 지원금", ("재난지원금", "긴급고용", "소상공인", "고용유지", "무급휴직", "청년 지원금", "지원금")),  # 6장
)


def _hits(text: str) -> list[int]:
    return [sum(text.count(word) for word in words) for _, words in INQUIRY_RULES]


def classify_inquiry(utterances: list[Utterance]) -> str:
    """발화 순서대로 받은 마스킹 확정 발화 → 장 이름 또는 「미분류」."""
    for u in utterances:
        if u.speaker != "customer":
            continue
        hits = _hits(u.text)
        best = max(hits)
        if best > 0:
            return INQUIRY_RULES[hits.index(best)][0]
    return UNCLASSIFIED
