# Requirement: C-5, QUA-1
"""2026-09-17 점검에서 드러난 C-5 구멍 — **누락**과 **과잉 마스킹**을 한 파일에 같이 고정한다.

출처는 셋이다. 문장을 지어내지 않고 실제로 걸린 모양을 옮겼다.
- 로컬 E2E 합성 통화(`scripts/persona_sim/dasan-v0`) — 이름·번지가 원문으로 자막·DB 에 남았다(SEC-1)
- 골든셋 `v1-150` 규칙 채점 — GS-056·412·413·415 누락, GS-409 유형 오분류
- AI Hub 민원 질의응답(validation 다산) 실제 발화 20,278건 — 규칙이 이름·주소로 **잘못** 가린 조각 상위

누락을 막으려고 규칙을 넓히면 자막이 지워진다. **두 방향을 같은 파일에서 본다** — 한쪽만 테스트하면
「전부 가린다」가 만점을 받는다(절대 원칙 10).
"""

import pytest

from masking.domain.services.masker import mask_text


def _masked(text):
    return mask_text(text)[0]


def _patterns(text):
    return [s.pattern for s in mask_text(text)[1]]


# ── P6 누락 ─────────────────────────────────────────────────────────────────

@pytest.mark.parametrize("text, names", [
    ("알겠어요. 제 이름은 김도윤이고요, 연락처는 010-0000-0103입니다.", ["김도윤"]),  # 말투 「이고요」
    ("저는 최지훈이고요 등본 발급 문의드려요", ["최지훈"]),                          # GS-412 문맥 「저는」
    ("신청인 이름은 한서윤으로 넣어주세요", ["한서윤"]),                              # GS-413 조사 「으로」
    ("그 김민준 씨가 어제 전화했었는데요", ["김민준"]),                               # GS-056 호칭 「씨」
    ("네, 김도윤 고객님. 다시 정리하면 인감 날인된 위임장", ["김도윤"]),             # 상담원이 부르는 호칭
    ("네, 제니 레예스 고객님. 신청서, 신분증 챙기세요.", ["제니", "레예스"]),         # 띄어 쓴 외국인 이름 + 호칭
    ("010 0000 0104. 이름 제니 레예스.", ["제니", "레예스"]),                          # 문맥 뒤 두 어절
    ("제 이름은 응우옌 티 란이에요. 주소는", ["응우옌", "티", "란"]),                 # 세 어절
    ("박성호요. 한별시 누리구 햇살로 45, 102동 1103호.", ["박성호"]),                  # 이름만 답한 발화
    ("한지영이요. 한별시 나래구 별빛로 88, 5층.", ["한지영"]),
    ("이순자예요.", ["이순자"]),
])
def test_P6_점검에서_놓친_이름을_잡는다(text, names):
    masked = _masked(text)
    for name in names:
        assert name not in masked, f"「{name}」 이 남았다: {masked}"
    assert "P6" in _patterns(text)


def test_P6_이름_뒤_말투는_남긴다():
    """「이고요」·「이에요」까지 가리면 문장이 끊긴다 — 기존 「이고」 규칙과 같은 이유."""
    assert _masked("알겠어요. 제 이름은 김도윤이고요, 연락처는").startswith("알겠어요. 제 이름은 ***이고요,")
    assert _masked("제 이름은 응우옌 티 란이에요. 주소는").endswith("이에요. 주소는")


def test_P6_문맥_뒤_긴_덩어리는_어절째_가린다():
    """오류 내성 곡선에서 뚫린 GS-037 — STT 가 이름 뒤를 뭉개 조사를 못 벗기면 예전엔 **통째로 버렸다.**
    문맥이 있는데 버리면 누락이다. 애매하면 가린다."""
    assert "박서연" not in _masked("제 이름은 박서연이곴 맞아요")


