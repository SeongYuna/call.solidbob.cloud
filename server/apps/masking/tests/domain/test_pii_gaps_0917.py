# ── P7 누락 — 도로명 뒤 건물번호 ─────────────────────────────────────────────

@pytest.mark.parametrize("text, leaked, kept", [
    ("우리 집 앞 한별시 가온구 은하로 7-3 앞에 잠깐 댔는데", "7-3", "앞에 잠깐"),
    ("박성호요. 한별시 누리구 햇살로 45, 102동 1103호.", "45", ""),
    ("한지영이요. 한별시 나래구 별빛로 88, 5층.", "88", ""),
    ("성북구 정릉로 77길 12에서 물이 새요", "77길", "에서 물이 새요"),            # GS-415
    ("제 이름은 응우옌 티 란이에요. 주소는 한별시 가온구 새솔로 12, 305호예요.", "12", "예요."),
])
def test_P7_도로명_뒤_건물번호까지_가린다(text, leaked, kept):
    masked = _masked(text)
    assert leaked not in masked, masked
    assert kept in masked, f"주소 뒤 말까지 가렸다: {masked}"
    assert "P7" in _patterns(text)


def test_P7_골든셋_건물번호도_가린다():
    assert "12" not in _masked("성북구 정릉로 77길 12에서 물이 새요")


