def test_P4_집_전화는_전화번호로_분류한다():
    """GS-409 — 02 로 시작하는 10자리를 계좌(P3)로 불렀다. 가려지긴 했지만 화면이 「계좌번호」라고 거짓말한다."""
    assert _patterns("집 전화 0221234567 로도 연락돼요") == ["P4"]


