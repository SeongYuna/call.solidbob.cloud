# Requirement: C-5, SEC-1, QUA-1
"""2026-09-22 최종 QA 에서 드러난 C-5 구멍 두 갈래 — 이름 끝 글자 누출(절대 규칙)과 「요청 (」 주변.

- `w6-c5-name-tail-leak`: E2E SYN-017 #12 `"저 이름 다나카 유이."` 가 확정 자막·DB 에 `"저 이름 *** *이."` 로 남았다.
  규칙(`name_detector._after_context`)이 「유이」 의 「이」 를 주격 조사로 벗겼다. 한 문장이 아니라 **갈래**로 고정한다 —
  띄어 쓴 외국인 이름이 조사처럼 보이는 한 음절(이·우·아)로 끝나는 것 · 「이」 로 끝나는 한국 이름 · 띄어쓰기로 갈린 이름.
- `w6-c5-overmask-request-word`: 운영 블랙리스트 사유 `"운영 점검용 테스트 요청 (정성윤, 09-22)"` 의 「요청」 이 가려졌다.
  **규칙이 아니라 NER 겹**이 한 일이다(`ai/apps/pii_ner` 테스트가 고정한다). 여기서는 규칙 쪽을 본다 — 규칙은 「요청」 을
  가리지 않고, 재현 중 드러난 **괄호 안 호칭 이름 누락**(`"(한가람 고객님)"`)을 잡는다.

09-17·09-18 파일과 같이 **두 방향을 같이 본다** — 누락만 보면 「전부 가린다」가 만점이다.
이름은 전부 지어낸 것이다.
"""

import pytest

from masking.domain.services.masker import mask_text


def _masked(text):
    return mask_text(text)[0]


def _patterns(text):
    return [s.pattern for s in mask_text(text)[1]]


def _leaked(text, name):
    """이름 구간에서 가려지지 않은 글자(공백 제외). 한 글자라도 남으면 누락이다(글자 단위)."""
    start = text.index(name)
    masked = _masked(text)
    return "".join(text[i] for i in range(start, start + len(name)) if masked[i] != "*" and not text[i].isspace())


# ── P6 누락 — 이름 끝 글자 ───────────────────────────────────────────────────

@pytest.mark.parametrize("text, name", [
    ("원본, 네. 알겠어요. 연락 주세요. 저 이름 다나카 유이. 전화 010 0000 0117.", "다나카 유이"),  # SYN-017 #12 원문
    ("저 이름 사토 유이.", "사토 유이"),                  # GS-421 — 홑 「이」 + 마침표
    ("제 이름은 스즈키 아이요.", "스즈키 아이"),          # GS-422 — 「이요」 를 벗기면 「아」 만 남는다
    ("성함이 응우옌 티 마이에요.", "응우옌 티 마이"),     # GS-423 — 세 어절 + 「이에요」
    ("제 이름은 응우옌 티 란이에요.", "응우옌 티 란"),    # SYN-002 #12
    ("이름이 다나카 유이에요.", "다나카 유이"),
    ("이름이 다나카 유이 맞아요", "다나카 유이"),
    ("이름이 다나카 사쿠라이고요", "다나카 사쿠라이"),    # 「이고요」 의 「이」 가 이름 끝일 수 있다
    ("제 이름은 김서이에요.", "김서이"),                  # GS-427 — 「이」 로 끝나는 한국 이름
    ("이름은 한소이.", "한소이"),                         # GS-429
])
def test_P6_이름_끝_글자_이_를_조사로_벗겨_흘리지_않는다(text, name):
    assert _leaked(text, name) == "", _masked(text)
    assert "P6" in _patterns(text)


@pytest.mark.parametrize("text, name", [
    ("이름은 다나카 유우입니다.", "다나카 유우"),         # GS-424 — 「니다」 를 동사 어미로 보고 둘째 어절을 통째로 흘렸다
    ("제 이름이 마리아 소피아요.", "마리아 소피아"),      # GS-425 — 「아요」 도 같다
    ("제 이름은 첸 메이이에요.", "첸 메이"),              # GS-426 — 한 음절 외국 성을 첫 어절이라 버렸다
    ("성함이 박 지우요.", "박 지우"),                     # GS-428 — STT 띄어쓰기로 갈린 한국 이름
])
def test_P6_조사처럼_끝나는_둘째_어절과_한_음절_성을_통째로_흘리지_않는다(text, name):
    assert _leaked(text, name) == "", _masked(text)


def test_P6_가려지는_것은_이름_끝_이_까지다():
    """과잉은 「이」 한 글자로 묶는다 — 「에요」·「요」 는 남긴다(자막이 읽혀야 한다)."""
    assert _masked("제 이름은 스즈키 아이요.") == "제 이름은 *** **요."
    assert _masked("제 이름은 응우옌 티 란이에요.") == "제 이름은 *** * **에요."
    assert _masked("제 이름은 김서이에요.") == "제 이름은 ***에요."
    assert _masked("이름은 다나카 유우입니다.") == "이름은 *** **입니다."


# ── 고친 뒤에도 그대로여야 하는 것 ───────────────────────────────────────────

def test_P6_세_글자_한국_이름_뒤_조사는_그대로_남긴다():
    """「이」 까지 가리는 것은 두 글자만 남을 때·이어진 어절·문장 끝뿐이다 — 흔한 세 글자 이름 + 조사는 그대로다."""
    assert _masked("제 이름은 박서연이고 번호는 알려드릴게요") == "제 이름은 ***이고 번호는 알려드릴게요"
    assert _masked("제 이름은 김민준이에요") == "제 이름은 ***이에요"


@pytest.mark.parametrize("text, kept", [
    ("제 이름은 김민준 맞아요", "맞아요"),     # 이름 뒤 서술어는 이름이 아니다(`_NOT_NAMES`)
    ("성함이 홍길동 맞으세요?", "맞으세요"),   # 「세요」 는 여전히 동사
])
def test_P6_이름_뒤_서술어는_남긴다(text, kept):
    assert kept in _masked(text)


@pytest.mark.parametrize("text", [
    "이름이나 나이는 몰라요",     # 첫 어절 한 글자 「나」 — 성씨가 아니다
    "이름은 잘 기억 안 나요",     # 「잘」
])
def test_P6_성씨가_아닌_한_글자_첫_어절은_여전히_버린다(text):
    assert "P6" not in _patterns(text), _masked(text)


# ── 「요청 (」 — 규칙 쪽 ──────────────────────────────────────────────────────

def test_P6_운영_사유_문장에서_규칙은_요청_을_가리지_않는다():
    """운영에서 「요청」 을 가린 것은 NER 겹이다(`ai/apps/pii_ner` — `_NOT_PERSON_WORDS`). 규칙은 처음부터 가리지 않았다 —
    괄호 안 문맥 없는 이름(「정성윤,」)은 규칙이 못 잡는 모양이라 NER 몫이다(09-17 파일 「문맥 없는 이름」 과 같은 한계)."""
    text = "운영 점검용 테스트 요청 (정성윤, 09-22) — 블랙리스트 확인"
    assert "테스트 요청 (" in _masked(text)


@pytest.mark.parametrize("text, name", [
    ("요청 (한가람 고객님) 건 확인 부탁해요", "한가람"),            # GS-431 — 「(」 뒤·「)」 앞이라 호칭 규칙이 못 봤다
    ("민원 처리 요청 (한가람 씨, 어제 접수) 확인해 주세요", "한가람"),
])
def test_P6_괄호_안_호칭_이름을_잡고_요청_은_남긴다(text, name):
    masked = _masked(text)
    assert name not in masked, masked
    assert "요청 (" in masked


def test_P6_이름_없는_요청_괄호는_아무것도_가리지_않는다():  # GS-430
    text = "민원 처리 요청 (지난주 접수 건) 진행 상황 좀 알려주세요"
    assert _masked(text) == text
