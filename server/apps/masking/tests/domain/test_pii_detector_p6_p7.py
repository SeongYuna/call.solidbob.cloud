"""P6(인명)·P7(상세주소) 탐지. **누락 0건이 절대 규칙**이다.

두 패턴은 [2.4절](/docs/02/)이 NER 로 정했지만 모델은 `ai/` 몫이라 규칙으로 바닥을 깔았다.
그래서 이 테스트는 **무엇을 잡는지만이 아니라 무엇을 못 잡는지도** 고정한다 —
못 잡는 범위를 테스트에 적어 두지 않으면 NER 이 붙어야 할 이유가 코드에서 사라진다.
"""

import pytest

from masking.domain.services.masker import mask_text


def _patterns(text):
    return [s.pattern for s in mask_text(text)[1]]


def _masked(text):
    return mask_text(text)[0]


# ── P7 상세주소 ──────────────────────────────────────────────────────────────

@pytest.mark.parametrize("text, leaked", [
    ("저희 집 주소가 서울시 강남구 테헤란로 123번지 456호예요", "강남구"),
    ("주소는 부산광역시 해운대구 우동 1234번지 입니다", "해운대구"),
    ("경기도 성남시 분당구 판교로 235 로 보내주세요", "판교로"),
    ("서울 종로구 세종대로 175 맞습니다", "세종대로"),
])
def test_P7_주소는_어절이_이어지면_통째로_가려진다(text, leaked):
    assert leaked not in _masked(text)
    assert "P7" in _patterns(text)


def test_P7_주소_뒤_조사는_먹지_않는다():
    """`"456호예요"` 에서 `"예요"` 까지 가리면 자막이 읽히지 않는다.

    번호 뒤 조사가 번호에 먹히던 문제(한글 수사)와 같은 종류다.
    """
    assert _masked("저희 집 주소가 서울시 강남구 테헤란로 123번지 456호예요").endswith("예요")


@pytest.mark.parametrize("text", [
    "그러므로 환불이 맞습니다",          # `로` 로 끝나지만 주소가 아니다
    "새로 신청하려고요",                 # 같은 이유
    "전국 어디로 보내도 되나요",         # 어절 하나뿐 — 이어지지 않는다
    "동 대표님께 여쭤볼게요",            # `동` 하나뿐
])
def test_P7_일상어를_주소로_보지_않는다(text):
    """어절 2개 이상 + 행정구역 표지를 요구한다. 자막이 통째로 지워지는 것을 막는다."""
    assert _masked(text) == text


# ── P6 인명 ─────────────────────────────────────────────────────────────────

@pytest.mark.parametrize("text, name", [
    ("제 이름은 김민준이고 진료기록 좀 확인해주세요", "김민준"),
    ("제 이름 박서연이고 번호는 010-2345-6789예요", "박서연"),
    ("성함이 홍길동입니다", "홍길동"),
    ("명의자는 최유나예요", "최유나"),
])
def test_P6_이름을_밝히는_문맥에서_잡는다(text, name):
    assert name not in _masked(text)
    assert "P6" in _patterns(text)


def test_P6_이름_뒤_조사는_먹지_않는다():
    """`"김민준이고"` 에서 `"이고"` 까지 가리면 문장이 끊긴다."""
    assert _masked("제 이름은 김민준이고 진료기록 좀 확인해주세요").startswith("제 이름은 ***이고")


@pytest.mark.parametrize("text", [
    "이름을 바꾸고 싶어요",              # 문맥어 뒤가 이름이 아니다 → 조사 제거 후 2자 미만
    "반품 접수 부탁드립니다",            # 문맥 자체가 없다
])
def test_P6_문맥이_없으면_한글을_가리지_않는다(text):
    """2~4자 한글을 문맥 없이 전부 가리면 **자막 자체가 못 쓰게 된다.**

    P5(인증번호)가 문맥을 요구하는 것과 같은 이유다.
    """
    assert _masked(text) == text


