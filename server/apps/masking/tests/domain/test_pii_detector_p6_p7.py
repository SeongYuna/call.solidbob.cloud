# ── 복합 ────────────────────────────────────────────────────────────────────

def test_한_발화에_이름과_번호가_같이_있으면_둘_다_잡는다():
    text = "제 이름 박서연이고 번호는 010-2345-6789예요 다시 연락 주세요"
    assert set(_patterns(text)) == {"P6", "P4"}
    assert "박서연" not in _masked(text) and "2345" not in _masked(text)
